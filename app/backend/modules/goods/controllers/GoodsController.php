            $cost_ratio = 0;
            if ($item['cost_price']) {
                $basic = bcsub($item['price'], $item['cost_price'], 2);
                $cost_ratio = bcdiv($basic, $item['cost_price'], 4) * 100;
            }
            $list[$key]['cost_ratio'] = $cost_ratio . "%";
            $sell_ratio = 0;
            if ($item['price']) {
                $basic = bcsub($item['price'], $item['cost_price'], 2);
                $sell_ratio = bcdiv($basic, $item['price'], 4) * 100;
