            return $this->errorJson('请填写模板名称!');
        }
        if(empty($input['checked_column'])){
            return $this->errorJson('请勾选导出字段!');
        }
        array_multisort(array_column($input['checked_column'],'weight'),SORT_DESC,$input['checked_column']);
        $input['checked_column'] = array_column($input['checked_column'],'value');
        if($input['id']){
            $exist = GoodsExportTemplate::editTemplate($input['id'],[
                'name' => $input['name'],
                'checked_column' => $input['checked_column']
            ],0,0);
        }else{
            $exist = GoodsExportTemplate::createTemplate([
                'name' => $input['name'],
                'checked_column' => $input['checked_column'],
            ]);
        }
        return $this->successJson('保存成功',['id' => $exist->id]);
    }

