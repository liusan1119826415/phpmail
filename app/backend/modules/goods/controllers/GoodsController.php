    /**
     * 根据导出模板获取导出内容
     * @param $set
     * @param $content
     * @param null $category
     * @return array|string|string[]
     */
    public function getExportContent($set,$content,$category=null){
        $cell=[];
        $options=[];
        $option=[];
        $tail=[];
        foreach($set as $val){
            switch($val){
                case 'id':
                    if(empty($content)){
                        $cell[]='商品ID';
                    }else{
                        $cell[]=$content->id;
                    }
                    break;
                case 'display_order':
                    if(empty($content)){
                        $cell[]='商品排序';
                    }else{
                        $cell[]=$content->display_order;
                    }
                    break;
                case 'title':
                    if(empty($content)){
                        $cell[]='商品名称';
                    }else{
                        $cell[]=$content->title;
                    }
                    break;
                case 'brand_id':
                    if(empty($content)){
                        $cell[]='品牌';
                    }else{
                        $cell[]= $content->hasOneBrand->name;
                    }
                    break;
                case 'alias':
                    if(empty($content)){
                        $cell[]='商品简称';
                    }else{
                        $cell[]= $content->alias;
                    }
                    break;
                case 'category':
                    if(empty($content)){
                        $cell=array_merge($cell,['一级分类','二级分类','三级分类']);
                    }else{
                        $cate = [];
                        foreach ($content->belongsToCategorys()->get() as $v) {
                            $cate[] = $category->getCateOrderByLevel($v['category_ids']);
                        }
                        $first=implode('|',array_column($cate,0));
                        $second=implode('|',array_column($cate,1));
                        $third=implode('|',array_column($cate,2));
                        $cell=array_merge($cell,[$first,$second,$third]);
                    }
                    break;
                case 'status':
                    if(empty($content)){
                        $cell[]='状态';
                    }else{
                        $cell[]= $content->status_name;
                    }
                    break;
                case 'sku':
                    if(empty($content)){
                        $cell[]='商品单位';
                    }else{
                        $cell[]= $content->sku;
                    }
                    break;
                case 'real_sales':
                    if(empty($content)){
                        $cell[]='销量';
                    }else{
                        $cell[]= $content->real_sales;
                    }
                    break;
                case 'option':
                    if(empty($content)){
                        $cell[]='商品规格标题';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]='单规格';
                        }else{
                            $option[]=array_column($content->hasManyOptions->toArray(),'title');

                        }
                    }
                    break;
                case 'stock':
                    if(empty($content)){
                        $cell[]='库存';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]=$content->stock;
                        }else{
                            $option[]=array_column($content->hasManyOptions->toArray(),'stock');
                        }
                    }
                    break;
                case 'price':
                    if(empty($content)){
                        $cell[]='现价';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]=$content->price;
                        }else {
                            $option[] = array_column($content->hasManyOptions->toArray(), 'product_price');
                        }
                    }
                    break;
                case 'market_price':
                    if(empty($content)){
                        $cell[]='原价';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]=$content->market_price;
                        }else {
                            $option[] = array_column($content->hasManyOptions->toArray(), 'market_price');
                        }
                    }
                    break;
                case 'cost_price':
                    if(empty($content)){
                        $cell[]='成本价';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]=$content->cost_price;
                        }else {
                            $option[] = array_column($content->hasManyOptions->toArray(), 'cost_price');
                        }
                    }
                    break;
                case 'goods_sn':
                    if(empty($content)){
                        $cell[]='商品编码';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]= $content->goods_sn;
                        }else{
                            if(!count($content->hasManyOptions)){
                                $cell[]=$content->goods_sn;
                            }else {
                                $option[] = array_column($content->hasManyOptions->toArray(), 'goods_sn');
                            }
                        }
                    }
                    break;
                case 'product_sn':
                    if(empty($content)){
                        $cell[]='商品条码';
                    }else{
                        if(!count($content->hasManyOptions)){
                            $cell[]= $content->product_sn;
                        }else{
                            if(!count($content->hasManyOptions)){
                                $cell[]=$content->product_sn;
                            }else {
                                $option[] = array_column($content->hasManyOptions->toArray(), 'product_sn');
                            }
                        }
                    }
                    break;
                case 'label':
                    if(empty($content)){
                        $cell[]='标签';
                    }else{
                        $label = [];
                        foreach ($content->hasManyGoodsFilter as $goodsFilter) {
                            if ($goodsFilter->hasOneSearchFilter) {
                                $label[] = $goodsFilter->hasOneSearchFilter->name;
                            }
                        }
                        $cell[]= implode(',',$label);
                    }
                    break;
                case 'point_max_deduction':
                    if(empty($content)){
                        $cell[]='积分抵扣最高比例';
                    }else{
                        $cell[]= $content->hasOneSale ? $content->hasOneSale->max_point_deduct : '';
                    }
                    break;
                case 'point_min_deduction':
                    if(empty($content)){
                        $cell[]='积分抵扣最低比例';
                    }else{
                        $cell[]= $content->hasOneSale ? $content->hasOneSale->min_point_deduct : '';
                    }
                    break;
                case 'free_shipping':
                    if(empty($content)){
                        $cell[]='是否包邮';
                    }else{
                        $cell[]= $content->hasOneGoodsDispatch->dispatch_type == 1 && $content->hasOneGoodsDispatch->dispatch_price <= 0 ? '是' : '否';
                    }
                    break;
            }
        }

//        ->with(['hasOneGoodsDispatch' => function ($query) {
//            return $query->select('goods_id','dispatch_type','dispatch_price');
//        }]);


        $count = count($option[0]);
        for($i=0;$i<$count;$i++){
            $options[$i]=array_column($option,$i);
        }

        if(!empty($content)){
            if(!empty($options)){
                $cell['option']=$options;
            }
            $cell[]=$tail;
        }
        return $cell;
    }
