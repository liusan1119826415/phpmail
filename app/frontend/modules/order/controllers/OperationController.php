//            $order = Order::find(\Yunshop::request()->orderId);
//            (new MiniMessageService($order,'',2,'订单取消通知'))->received();
//        }
        return $this->successJson();
    }

    public function restore()
    {
        $restrictAccess = \app\common\services\RequestTokenService::limitRepeat('f_order_restore'. $this->params['order_id']);

        if (!$restrictAccess) {
            throw new AppException('短时间内重复操作，请等待10秒后再操作');
        }

        OrderService::orderRestore($this->params['order_id']);

        return $this->successJson();
    }
}