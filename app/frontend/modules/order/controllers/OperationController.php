        if (!$restrictAccess) {
            throw new AppException('操作过于频繁，请等待60秒后再操作');
        }


        $restrictAccess = \app\common\services\RequestTokenService::limitRepeat('f_order_close'. $this->params['order_id'],60);

		if (!$restrictAccess) {
			throw new AppException('短时间内重复操作，请等待60秒后再操作');
		}

        OrderService::orderClose($this->params);
		//更新项目的订单状态
        $order = Order::find($this->params['order_id']);
        $project = Project::where(['id'=>$order->project_id])->update([
            'order_status'=>0,
            'order_id'=>0
        ]);
        Redis::del("user:{$userId}:active_project_1");
        //$ingress = \Yunshop::request()->ingress;
